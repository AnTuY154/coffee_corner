import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const src=p=>readFileSync(p,'utf8');
const immersive=src('components/3d-shop/immersive-shop.tsx');
const world=src('components/3d-shop/world.tsx');
const characters=src('components/3d-shop/characters.tsx');
const menu=src('components/3d-shop/in-world-menu.tsx');
const home=src('app/page.tsx');
const layout=src('app/layout.tsx');
assert.match(home, /<ImmersiveShop\s*\/>/,'root route must be the 3D shop');
assert.doesNotMatch(layout, /<SiteHeader|<SiteFooter/,'global 2D chrome must not appear');
assert.doesNotMatch(immersive, /shop-menu-paper|shop-hud-top|shop-hud-bottom|Menu 2D/,'no 2D menu/HUD');
assert.match(world, /<InWorldMenu\s/,'3D menu must live inside Canvas');
assert.match(world, /<PlayerAvatar\s/,'third person player must exist');
assert.match(world, /<CatBarista\s/,'cat needs to staff the counter');
assert.match(world, /<WalkingCustomer\s/,'scene must include a moving customer');
assert.match(world, /<GardenDog\s/,'scene should be lively');
assert.match(world,/ACESFilmicToneMapping/,'cinematic scene uses physically based tone mapping');
assert.match(world,/cameraAnchor\(c,compact\)/,'camera uses verified heading-relative orbit');
assert.match(characters, /Math\.sin\(t\*2\.3\)/,'cat must animate');
assert.match(characters, /amber|#f0bc63/i,'amber eye pigment');
assert.match(characters,/meshPhysicalMaterial color="#e5a84d"/,'cat has clear-coated 3D irises');
assert.match(characters,/juiceStream\.current\.visible/,'cat pour animation has real 3D juice geometry');
assert.match(characters,/strideWeight\.current=THREE\.MathUtils\.damp/,'player walk transitions have damping');
assert.match(world,/variant={1}/,'desktop should render a second customer');
assert.match(immersive, /onApproach=\{goToCounter\}/,'touch navigation must exist');
assert.match(menu,/onClick=\{e=>\{e\.stopPropagation\(\);onClick\(\);\}\}/,'3D menu hit targets must include text children');
assert.match(menu, /products\.filter\(p=>p\.season===season\)/,'all products accessible by season');
assert.match(menu, /onClick={onCheckout}/,'in-world cart can proceed to real order flow');
console.log('PASS: immersive-only world, visible player, animated cat/NPC, in-world 3D order menu and mobile entry.');
