import { chromium } from '@playwright/test';
import { mkdirSync, renameSync } from 'node:fs';
mkdirSync('qa-production/video',{recursive:true});
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1366,height:768},recordVideo:{dir:'qa-production/video',size:{width:1366,height:768}}});
const page=await context.newPage();
await page.goto('https://hblab-coffee.vercel.app/');
await page.locator('.ve2d-pixi-pets[data-visible="true"]').waitFor();
await page.waitForTimeout(2500);
await page.locator('.ve2d-stage').screenshot({path:'qa-production/live-01.png'});
await page.locator('.ve2d-hotspot[data-target="dog"]').click();
await page.keyboard.press('Escape');
await page.mouse.move(-20,-20);
await page.waitForTimeout(4000);
await page.locator('.ve2d-stage').screenshot({path:'qa-production/live-02.png'});
await page.waitForTimeout(4000);
await page.locator('.ve2d-stage').screenshot({path:'qa-production/live-03.png'});
const video=page.video();
await context.close();
await video.saveAs('qa-production/animation-production.webm');
await browser.close();
console.log('Saved production animation video and three sequential screenshots');
